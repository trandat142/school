public class ViDuToanTu {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        int c;

        System.out.println(c = a);   // 10
        System.out.println(b += a);  // 30
        System.out.println(b -= a);  // 20
        System.out.println(b *= a);  // 200
        System.out.println(b /= a);  // 20

        System.out.println(10 % 3);  // 1
    }
}
